    private void jButtonEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEntrarActionPerformed
        String email = txtEmail.getText().trim();
        String senha = txtSenha.getText().trim();

        if (email.isEmpty() || senha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos.");
            return;
        }

        try {
            if (iencurtador != null && iencurtador.login(email, senha)) {
                new ClienteInterface(email, iencurtador).setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "E-mail ou senha inválidos.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jButtonEntrarActionPerformed

    private void jButtonCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCadastrarActionPerformed
    String email = txtEmail.getText().trim();
    String senha = txtSenha.getText().trim();

    if (email.isEmpty() || senha.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha e-mail e senha para cadastrar.");
        return;
    }

    try {
        if (iencurtador.existeUsuario(email)) {
            JOptionPane.showMessageDialog(this, "E-mail já cadastrado.");
            return;
        }

        String nome = JOptionPane.showInputDialog(this, "Informe seu Nome:");
        if (nome == null || nome.trim().isEmpty()) return;

        String dataNasc = JOptionPane.showInputDialog(this, "Informe sua Data de Nascimento:");
        if (dataNasc == null) dataNasc = "";

        if (iencurtador.cadastrar(new model.Pessoa(nome, dataNasc, email), senha)) {
            JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
    }
    }//GEN-LAST:event_jButtonCadastrarActionPerformed

